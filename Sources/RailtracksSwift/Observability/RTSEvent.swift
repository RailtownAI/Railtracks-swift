import Foundation

// MARK: - RTSEvent

/// One observability event, as it goes on the wire.
///
/// A direct port of the Python engine's `Event` dataclass (`observability/models.py`):
/// the same seven fields, the same JSON keys, and the same encoding. Swift properties are
/// camelCase; ``CodingKeys`` maps them to Python's snake_case so the emitted JSON is
/// byte-comparable with `Event.encode()`.
///
/// The envelope is deliberately untyped — ``payload`` is a flat bag of JSON values. The
/// typed events in `Observability/Events/` produce that bag; ``session(_:sessionID:)``
/// wraps one.
///
/// `encode(to:)` is hand-written rather than generated by `@EncodeNulls`, because two
/// things need controlling at once: `parent_scope_id` must serialize as `null` rather than
/// being omitted (Python always writes the key), and `stamp` must use Python's
/// `datetime.isoformat()` spelling rather than `Date`'s default encoding.
public struct RTSEvent: Sendable, Codable {
    /// Dotted event name, e.g. `"node.creation"`.
    public let eventType: String
    /// The kind of scope this event belongs to.
    public let scopeType: RTSEventScope
    /// Identifier of the scope instance — the session id, for session-scoped events.
    public let scopeID: String
    /// Unique identifier for this event.
    public let eventID: String
    /// When the event was created.
    public let stamp: Date
    /// Enclosing scope, for nested scopes. `null` on the wire when absent.
    public let parentScopeID: String?
    /// Event-specific fields, already flattened to snake_case keys.
    public let payload: [String: RTSValue]

    enum CodingKeys: String, CodingKey {
        case eventType = "event_type"
        case scopeType = "scope_type"
        case scopeID = "scope_id"
        case eventID = "event_id"
        case stamp
        case parentScopeID = "parent_scope_id"
        case payload
    }

    public init(
        eventType: String,
        scopeType: RTSEventScope,
        scopeID: String,
        eventID: String = UUID().uuidString,
        stamp: Date = RTSEventTimestamp.now(),
        parentScopeID: String? = nil,
        payload: [String: RTSValue] = [:]
    ) {
        self.eventType = eventType
        self.scopeType = scopeType
        self.scopeID = scopeID
        self.eventID = eventID
        self.stamp = stamp
        self.parentScopeID = parentScopeID
        self.payload = payload
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        self.eventType = try container.decode(String.self, forKey: .eventType)
        self.scopeType = try container.decode(RTSEventScope.self, forKey: .scopeType)
        self.scopeID = try container.decode(String.self, forKey: .scopeID)
        self.eventID = try container.decode(String.self, forKey: .eventID)
        let stampText = try container.decode(String.self, forKey: .stamp)
        guard let stamp = RTSEventTimestamp.date(from: stampText) else {
            throw DecodingError.dataCorruptedError(
                forKey: .stamp,
                in: container,
                debugDescription: "Expected an ISO-8601 timestamp, got \"\(stampText)\""
            )
        }
        self.stamp = stamp
        self.parentScopeID = try container.decodeIfPresent(String.self, forKey: .parentScopeID)
        self.payload = try container.decode([String: RTSValue].self, forKey: .payload)
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(eventType, forKey: .eventType)
        try container.encode(scopeType, forKey: .scopeType)
        try container.encode(scopeID, forKey: .scopeID)
        try container.encode(eventID, forKey: .eventID)
        try container.encode(RTSEventTimestamp.isoString(from: stamp), forKey: .stamp)
        // Encoded rather than omitted when nil — Python's `encode()` always writes the key.
        try container.encode(parentScopeID, forKey: .parentScopeID)
        try container.encode(payload, forKey: .payload)
    }
}

// MARK: - RTSEvent session scoping

extension RTSEvent {
    /// Wraps a typed event in a session-scoped envelope.
    ///
    /// Mirrors the Python engine's `make_session_event`
    /// (`observability_bridge/_factory.py`).
    public static func session(
        _ event: some RTSObservabilityEvent,
        sessionID: String
    ) -> RTSEvent {
        RTSEvent(
            eventType: event.eventType,
            scopeType: .session,
            scopeID: sessionID,
            payload: event.encodePayload()
        )
    }
}
